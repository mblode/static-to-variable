SEMANTIC_CARRIER_SUFFIX = re.compile(r"^(?P<owner>.+)\.stv-semantic\d+x$")

# ufomerge emits ``.ssNN`` copies; skip those plus our own ``.stv-semantic``
# carriers so they are not treated as independent interpolating masters.
_SKIP_UFO_SUFFIXES = (".stv-semantic", ".ss01", ".ss02", ".ss03", ".ss04", ".ss05")

T = TypeVar("T")

# STAT axis-value flags (OT spec).
ELIDABLE_AXIS_VALUE_NAME = 0x0002

# Default Regular STAT location when the recipe does not name Regular.
_DEFAULT_REGULAR_LOCATION: dict[str, float] = {"wght": 400.0, "wdth": 100.0, "opsz": 12.0}

# Default Italic STAT location (same as Regular, plus italic).
_DEFAULT_ITALIC_LOCATION: dict[str, float] = {
    "wght": 400.0,
    "wdth": 100.0,
    "opsz": 12.0,
    "ital": 1.0,
}

# STAT axis ordering: wght, wdth, opsz, ital.  Extra axes (slnt, GRAD, …)
# are appended in recipe order after these.
_STAT_AXIS_ORDER = ("wght", "wdth", "opsz", "ital")

# Per-axis flags for STAT AxisValue records.
# opsz is OlderSiblingFontAttribute (0x0001) so applications that do not
# understand optical size still pick Regular at the default opsz.
_STAT_AXIS_FLAGS: dict[str, int] = {"opsz": 0x0001}


def _semantic_carrier_owner(name: str) -> str | None:
    match = SEMANTIC_CARRIER_SUFFIX.match(name)
    return None if match is None else match.group("owner")


