def _write_named_instances(tt_font: TTFont, recipe: AxisRecipe) -> None:
    if "fvar" not in tt_font:
        return
    fvar = tt_font["fvar"]
    existing = {tuple(sorted(i.coordinates.items())): i for i in fvar.instances}
    for name, loc in recipe.named_instances().items():
        design = _design_location(recipe, loc.as_mapping())
        key = tuple(sorted(design.items()))
        if key in existing:
            existing[key].name = name
            continue
        inst = NamedInstance()
        inst.coordinates = design
        inst.name = name
        fvar.instances.append(inst)


def _sync_italic_angle(tt_font: TTFont, recipe: AxisRecipe) -> None:
    if "post" not in tt_font:
        return
    italic = recipe.location_of("Italic")
    if italic is None:
        return
    if italic.as_mapping().get("ital", 0) >= 0.5:
        tt_font["post"].italicAngle = tt_font["post"].italicAngle or -12.0
