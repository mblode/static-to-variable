"""Build a variable font from static instances plus a piecewise-linear axis recipe.

The compiler owns:

- named instances from the axis recipe
- per-master location tables (avar / STAT / fvar)
- ``STAT`` axis values (Regular / Italic) plus optional ``elidedFallbackNameID``
- OS/2 usWeightClass / usWidthClass and italic-angle bookkeeping
- an AVAR2 piecewise-linear axis map from the recipe, compiled through
  ``fonttools.varLib.avar.compute_uncommon_plan``

Masters are generated by interpolating the registered extrema (Regular, Bold, Light
when present, plus Italic counterparts) at the recipe's piecewise-linear
coordinates.  Variable features (rvrn / rlig) are compiled from the same recipe.

Static masters that only exist as Regular (no Light / Bold extrema) are skipped:
there is no independent source to interpolate against, so they cannot be placed
on a variable axis.  The builder logs a warning and continues with the rest of
the family.
"""

